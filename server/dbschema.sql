-- Index 1: Primary timestamp index (MOST IMPORTANT for pagination)
-- This is critical for fast ORDER BY timestamp queries
CREATE INDEX IF NOT EXISTS idx_events_timestamp 
ON object_detection_events(timestamp DESC);

-- Index 2: Camera + timestamp composite index
-- Used when filtering by camera_id with pagination
CREATE INDEX IF NOT EXISTS idx_events_camera_timestamp 
ON object_detection_events(camera_id, timestamp DESC);

-- Index 3: Object class + timestamp composite index
-- Used when filtering by object_class_name with pagination
CREATE INDEX IF NOT EXISTS idx_events_object_timestamp 
ON object_detection_events(object_class_name, timestamp DESC);

-- Index 4: Camera name + timestamp composite index
-- Used when filtering by camera_name with pagination
CREATE INDEX IF NOT EXISTS idx_events_camera_name_timestamp 
ON object_detection_events(camera_name, timestamp DESC);

-- Index 5: Covering index (optional but recommended)
-- Includes frequently accessed columns for index-only scans
CREATE INDEX IF NOT EXISTS idx_events_covering 
ON object_detection_events(timestamp DESC, camera_id, object_class_name, confidence)
INCLUDE (camera_name, tracker_id, bbox_x, bbox_y, bbox_width, bbox_height);

