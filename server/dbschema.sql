create table public.object_detection_events (
  id bigserial not null,
  camera_id integer not null,
  camera_name text not null,
  camera_url text null,
  timestamp timestamp with time zone not null default now(),
  object_class_id integer not null,
  object_class_name text not null,
  confidence real not null,
  bbox_x real not null default 0,
  bbox_y real not null default 0,
  bbox_width real not null default 0,
  bbox_height real not null default 0,
  frame_width integer not null default 0,
  frame_height integer not null default 0,
  session_id uuid null,
  detection_metadata jsonb null default '{}'::jsonb,
  created_at timestamp with time zone not null default now(),
  constraint object_detection_events_pkey primary key (id),
  constraint object_detection_events_confidence_check check (
    (
      (confidence >= (0)::double precision)
      and (confidence <= (1)::double precision)
    )
  )
) TABLESPACE pg_default;

create index IF not exists idx_detection_events_camera_id on public.object_detection_events using btree (camera_id) TABLESPACE pg_default;

